import tkinter as tk

from config import (
    APP_NAME,
    LIGHT,
)

from state import state

from services.settings_service import (
    load_theme,
)


# ============================================================
# START APPLICATION
# ============================================================

def start_app():
    """
    Запускает главное окно BahonIQ.
    """

    # --------------------------------------------------------
    # ROOT
    # --------------------------------------------------------

    root = tk.Tk()

    state.root = root


    # --------------------------------------------------------
    # WINDOW
    # --------------------------------------------------------

    root.title(
        APP_NAME
    )

    root.geometry(
        "1100x760"
    )

    root.minsize(
        950,
        680
    )

    root.configure(
        bg=LIGHT
    )


    # --------------------------------------------------------
    # MAXIMIZE
    # --------------------------------------------------------

    try:

        root.state(
            "zoomed"
        )

    except Exception:

        pass


    # --------------------------------------------------------
    # LOAD SETTINGS
    # --------------------------------------------------------

    load_theme()


    # --------------------------------------------------------
    # MAIN WINDOW
    # --------------------------------------------------------

    from app.main_window import MainWindow


    MainWindow(
        root
    )


    # --------------------------------------------------------
    # START LOOP
    # --------------------------------------------------------

    root.mainloop()