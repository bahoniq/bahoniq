def _get_conn() -> sqlite3.Connection:
    """Создаёт подключение к SQLite с поддержкой внешних ключей и Row-фабрикой."""
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(str(DB_PATH), timeout=30.0)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON;")
    return conn


def init_wiki_db() -> None:
    """Инициализирует таблицы wiki_topics и wiki_articles, при пустой БД загружает стартовый набор."""
    with _db_lock:
        conn = _get_conn()
        try:
            conn.executescript(
                """
                CREATE TABLE IF NOT EXISTS wiki_topics (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    name TEXT UNIQUE NOT NULL,
                    created_at TEXT NOT NULL
                );

                CREATE TABLE IF NOT EXISTS wiki_articles (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    topic_id INTEGER NOT NULL,
                    title TEXT NOT NULL,
                    content TEXT NOT NULL,
                    source_filename TEXT DEFAULT '',
                    created_at TEXT NOT NULL,
                    FOREIGN KEY (topic_id) REFERENCES wiki_topics(id) ON DELETE CASCADE
                );

                CREATE INDEX IF NOT EXISTS idx_wiki_articles_topic ON wiki_articles(topic_id);
                """
            )
            conn.commit()

            count_row = conn.execute("SELECT COUNT(*) AS cnt FROM wiki_articles").fetchone()
            total_articles = count_row["cnt"] if count_row else 0

            if total_articles == 0:
                seed_data = DEFAULT_SEED_TOPICS
                if SEED_JSON_PATH.is_file():
                    try:
                        loaded = json.loads(SEED_JSON_PATH.read_text(encoding="utf-8"))
                        if isinstance(loaded, list) and loaded:
                            seed_data = loaded
                    except Exception as exc:
                        LOGGER.warning("Не удалось прочитать wiki_seed.json: %s", exc)

                now_iso = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
                for topic_item in seed_data:
                    t_name = str(topic_item.get("name", "")).strip()
                    if not t_name:
                        continue
                    conn.execute(
                        "INSERT OR IGNORE INTO wiki_topics (name, created_at) VALUES (?, ?)",
                        (t_name, now_iso),
                    )
                    t_row = conn.execute(
                        "SELECT id FROM wiki_topics WHERE name = ?", (t_name,)
                    ).fetchone()
                    if not t_row:
                        continue
                    t_id = t_row["id"]
                    for art in topic_item.get("articles", []):
                        a_title = str(art.get("title", "")).strip()
                        a_content = str(art.get("content", "")).strip()
                        a_src = str(art.get("source_filename", "")).strip()
                        if a_title and a_content:
                            conn.execute(
                                """
                                INSERT INTO wiki_articles (topic_id, title, content, source_filename, created_at)
                                VALUES (?, ?, ?, ?, ?)
                                """,
                                (t_id, a_title, a_content, a_src, now_iso),
                            )
                conn.commit()
                _export_seed_snapshot_unlocked(conn)
        finally:
            conn.close()


def _export_seed_snapshot_unlocked(conn: sqlite3.Connection) -> None:
    """Синхронизирует содержимое SQLite в JSON-снимок для облачной сохранности."""
    try:
        topics_rows = conn.execute(
            "SELECT id, name FROM wiki_topics ORDER BY id ASC"
        ).fetchall()
        export_list = []
        for t in topics_rows:
            arts = conn.execute(
                """
                SELECT title, content, source_filename
                FROM wiki_articles
                WHERE topic_id = ?
                ORDER BY id ASC
                """,
                (t["id"],),
            ).fetchall()
            if arts:
                export_list.append({
                    "name": t["name"],
                    "articles": [
                        {
                            "title": a["title"],
                            "content": a["content"],
                            "source_filename": a["source_filename"] or "",
                        }
                        for a in arts
                    ],
                })
        SEED_JSON_PATH.write_text(
            json.dumps(export_list, ensure_ascii=False, indent=2),
            encoding="utf-8",
        )
    except Exception as exc:
        LOGGER.warning("Не удалось сохранить снимок wiki_seed.json: %s", exc)


def get_wiki_tree() -> dict[str, Any]:
    """Возвращает дерево всех тем (wiki_topics) и заголовков вложенных статей (wiki_articles)."""
    init_wiki_db()
    conn = _get_conn()
    try:
        topics_rows = conn.execute(
            "SELECT id, name, created_at FROM wiki_topics ORDER BY id ASC"
        ).fetchall()
        articles_rows = conn.execute(
            """
            SELECT id, topic_id, title, source_filename, created_at
            FROM wiki_articles
            ORDER BY id ASC
            """
        ).fetchall()

        by_topic: dict[int, list[dict[str, Any]]] = {}
        for a in articles_rows:
            by_topic.setdefault(a["topic_id"], []).append({
                "id": a["id"],
                "topic_id": a["topic_id"],
                "title": a["title"],
                "source_filename": a["source_filename"] or "",
                "created_at": a["created_at"],
            })

        topics_out = []
        for t in topics_rows:
            t_arts = by_topic.get(t["id"], [])
            if t_arts:
                topics_out.append({
                    "id": t["id"],
                    "name": t["name"],
                    "created_at": t["created_at"],
                    "article_count": len(t_arts),
                    "articles": t_arts,
                })

        return {
            "total_topics": len(topics_out),
            "total_articles": len(articles_rows),
            "topics": topics_out,
        }
    finally:
        conn.close()


def get_article(article_id: int) -> dict[str, Any] | None:
    """Возвращает полную запись статьи по её ID."""
    init_wiki_db()
    conn = _get_conn()
    try:
        row = conn.execute(
            """
            SELECT a.id, a.topic_id, t.name AS topic_name, a.title, a.content,
                   a.source_filename, a.created_at
            FROM wiki_articles a
            JOIN wiki_topics t ON t.id = a.topic_id
            WHERE a.id = ?
            """,
            (article_id,),
        ).fetchone()
        if not row:
            return None
        return dict(row)
    finally:
        conn.close()


def _get_or_create_topic_id(conn: sqlite3.Connection, topic_name: str, now_iso: str) -> tuple[int, bool]:
    """Находит существующую тему без учёта регистра или создаёт новую."""
    clean_name = re.sub(r"\s+", " ", topic_name.strip()) or "Общие инструкции Platonus"
    existing = conn.execute(
        "SELECT id, name FROM wiki_topics"
    ).fetchall()
    for row in existing:
        if row["name"].strip().lower() == clean_name.lower():
            return row["id"], False

    conn.execute(
        "INSERT INTO wiki_topics (name, created_at) VALUES (?, ?)",
        (clean_name, now_iso),
    )
    new_row = conn.execute(
        "SELECT id FROM wiki_topics WHERE name = ?", (clean_name,)
    ).fetchone()
    return int(new_row["id"]), True


def update_article(article_id: int, title: str, content: str, topic_name: str | None = None) -> dict[str, Any]:
    """Обновляет заголовок, текст и (опционально) тему статьи."""
    init_wiki_db()
    clean_title = title.strip()
    clean_content = content.strip()
    if not clean_title or not clean_content:
        raise ValueError("Заголовок и текст инструкции не могут быть пустыми.")

    now_iso = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    with _db_lock:
        conn = _get_conn()
        try:
            current = conn.execute(
                "SELECT id, topic_id FROM wiki_articles WHERE id = ?", (article_id,)
            ).fetchone()
            if not current:
                raise ValueError(f"Статья #{article_id} не найдена.")

            target_topic_id = current["topic_id"]
            if topic_name and topic_name.strip():
                target_topic_id, _ = _get_or_create_topic_id(conn, topic_name, now_iso)

            conn.execute(
                """
                UPDATE wiki_articles
                SET topic_id = ?, title = ?, content = ?
                WHERE id = ?
                """,
                (target_topic_id, clean_title, clean_content, article_id),
            )
            # Удаляем пустые темы
            conn.execute(
                """
                DELETE FROM wiki_topics
                WHERE id NOT IN (SELECT DISTINCT topic_id FROM wiki_articles)
                """
            )
            conn.commit()
            _export_seed_snapshot_unlocked(conn)
        finally:
            conn.close()

    updated = get_article(article_id)
    if not updated:
        raise ValueError("Ошибка чтения обновлённой статьи.")
    return updated


def delete_article(article_id: int) -> bool:
    """Удаляет статью по ID и очищает пустые темы."""
    init_wiki_db()
    with _db_lock:
        conn = _get_conn()
        try:
            cur = conn.execute("DELETE FROM wiki_articles WHERE id = ?", (article_id,))
            deleted = cur.rowcount > 0
            conn.execute(
                """
                DELETE FROM wiki_topics
                WHERE id NOT IN (SELECT DISTINCT topic_id FROM wiki_articles)
                """
            )
            conn.commit()
            if deleted:
                _export_seed_snapshot_unlocked(conn)
            return deleted
        finally:
            conn.close()


