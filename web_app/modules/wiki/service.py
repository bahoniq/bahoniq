def _tokenize_query(text: str) -> set[str]:
    """Токенизирует запрос с сохранением 2-буквенных терминов Платонуса (РК, НБ, ОП, ОР, ВК) и основ слов."""
    words = re.findall(r"[а-яА-ЯёЁa-zA-Z0-9]{2,}", text.lower().replace("ё", "е"))
    tokens: set[str] = set()
    for w in words:
        if w in STOP_WORDS:
            continue
        tokens.add(w)
        # Если типа рк1, рк2 -> добавляем также 'рк'
        m = re.match(r"^([а-яa-z]{2,})\d+$", w)
        if m:
            tokens.add(m.group(1))
        if len(w) > 4:
            stem = re.sub(
                r"(ами|ями|ов|ев|ей|ам|ям|ом|ем|ой|ия|ие|ии|ью|ый|ий|ая|ое|ые|ую|юю|ть|ться|ет|ут|ют|ят|ат|ение|ание)$",
                "",
                w,
            )
            if len(stem) >= 3:
                tokens.add(stem)
    return tokens


def _expand_synonyms(tokens: set[str]) -> set[str]:
    """Расширяет поисковые токены синонимами терминов АИС Platonus для максимальной точности."""
    expanded = set(tokens)
    synonym_map = {
        "рк": {"рубежн", "ведомост", "рейтинг", "допуск", "спз", "рк1", "рк2"},
        "рубежн": {"рк", "ведомост", "рейтинг", "спз"},
        "ведомост": {"рк", "рубежн", "экзамен", "закрыт", "подписа"},
        "нб": {"пропуск", "посещаем", "журнал", "оценк", "ячейк"},
        "оценк": {"журнал", "балл", "нб", "выстав"},
        "журнал": {"оценк", "нб", "дата", "занят", "ктп"},
        "силлабус": {"умкд", "ктп", "файл", "утвержд"},
        "умкд": {"силлабус", "ктп"},
        "привяз": {"закреп", "нагрузк", "преподавател", "дисциплин"},
        "закреп": {"привяз", "нагрузк", "преподавател", "дисциплин"},
        "преподавател": {"ппс", "закреп", "нагрузк"},
        "ппс": {"преподавател", "нагрузк", "кафедр"},
        "корпус": {"здани", "аудитор", "инфраструктур"},
        "общежит": {"заселен", "комнат", "койк", "инфраструктур"},
        "групп": {"гоп", "оп", "поток", "куратор", "эдвайзер"},
        "гоп": {"оп", "групп", "образовательн"},
        "иуп": {"регистрац", "электив", "дисциплин", "пререквизит"},
        "парол": {"сброс", "разблокир", "вход", "логин", "учетн"},
    }
    for t in list(tokens):
        for key, syns in synonym_map.items():
            if t == key or (len(key) >= 4 and t.startswith(key)):
                expanded.update(syns)
    return expanded


def search_relevant_articles(query: str, top_k: int = 5) -> list[dict[str, Any]]:
    """Находит наиболее подходящие статьи в таблице wiki_articles."""
    init_wiki_db()
    base_tokens = _tokenize_query(query)
    all_tokens = _expand_synonyms(base_tokens)
    q_lower = query.lower().replace("ё", "е").strip()

    conn = _get_conn()
    try:
        rows = conn.execute(
            """
            SELECT a.id, a.topic_id, t.name AS topic_name, a.title, a.content,
                   a.source_filename, a.created_at
            FROM wiki_articles a
            JOIN wiki_topics t ON t.id = a.topic_id
            ORDER BY a.id ASC
            """
        ).fetchall()
    finally:
        conn.close()

    scored: list[dict[str, Any]] = []
    for row in rows:
        art = dict(row)
        title_low = art["title"].lower().replace("ё", "е")
        topic_low = art["topic_name"].lower().replace("ё", "е")
        content_low = art["content"].lower().replace("ё", "е")

        title_words = _tokenize_query(title_low)
        topic_words = _tokenize_query(topic_low)
        content_words = _tokenize_query(content_low)

        score = 0.0

        # Прямое вхождение фразы
        if len(q_lower) >= 3 and q_lower in title_low:
            score += 45.0
        if len(q_lower) >= 3 and q_lower in content_low:
            score += 25.0

        # Совпадение по основным токенам запроса
        for bt in base_tokens:
            if bt in title_words or bt in title_low:
                score += 18.0
            if bt in topic_words or bt in topic_low:
                score += 10.0
            if bt in content_words or bt in content_low:
                score += 8.0

        # Совпадение по расширенным синонимам
        for st in all_tokens - base_tokens:
            if st in title_words or st in title_low:
                score += 7.0
            if st in content_words or st in content_low:
                score += 3.5

        if score > 0:
            art["score"] = score
            scored.append(art)

    scored.sort(key=lambda x: x["score"], reverse=True)
    return scored[:top_k]


def ask_wiki(query: str) -> dict[str, Any]:
    """Ищет релевантные инструкции в БД и генерирует чёткий пошаговый ответ строго по базе знаний."""
    clean_q = query.strip()
    if not clean_q:
        raise ValueError("Введите вопрос по Platonus.")

    matched = search_relevant_articles(clean_q, top_k=5)

    # Получаем также полный оглавлений всех статей для общего контекста
    tree = get_wiki_tree()
    all_titles_context = []
    for t in tree.get("topics", []):
        for a in t.get("articles", []):
            all_titles_context.append(f"- [{t['name']}] {a['title']} (ID: {a['id']})")
    catalog_str = "\n".join(all_titles_context)

    if not matched:
        return {
            "answer": (
                "В загруженных инструкциях базы знаний Platonus информации по данному запросу не найдено.\n\n"
                "**Рекомендация:** Попробуйте уточнить формулировку вопроса или загрузите соответствующую инструкцию "
                "через кнопку **«+ Загрузить инструкции»** в левой панели."
            ),
            "provider": "database",
            "sources": [],
        }

    # Формируем контекст найденных статей
    records_blocks = []
    for idx, art in enumerate(matched, start=1):
        records_blocks.append(
            f"=== ЗАПИСЬ #{idx} (ID статьи: {art['id']}) ===\n"
            f"Тема: {art['topic_name']}\n"
            f"Название статьи: «{art['title']}»\n"
            f"Исходный файл: {art.get('source_filename') or 'База знаний Work Center'}\n"
            f"Текст инструкции:\n{art['content']}\n"
        )
    records_context = "\n\n".join(records_blocks)

    system_prompt = (
        "Ты — эксперт техподдержки Platonus. Отвечай строго на основе переданных записей из базы знаний. "
        "Дай чёткий, пошаговый ответ на вопрос пользователя (используй нумерованные списки и выделяй названия разделов меню и кнопок **жирным шрифтом**). "
        "В конце укажи, из какой статьи базы знаний взят ответ. "
        "Если информации в записях нет — честно скажи об этом, не выдумывай."
    )

    user_prompt = (
        f"ОГЛАВЛЕНИЕ ВСЕХ СТАТЕЙ В БАЗЕ ЗНАНИЙ:\n{catalog_str}\n\n"
        f"НАЙДЕННЫЕ РЕЛЕВАНТНЫЕ ЗАПИСИ ИЗ БАЗЫ ЗНАНИЙ:\n{records_context}\n\n"
        f"ВОПРОС ПОЛЬЗОВАТЕЛЯ:\n{clean_q}\n\n"
        f"Дай точный пошаговый ответ строго по тексту записей выше и в конце укажи точное название статьи-источника:"
    )

    provider = "database"
    answer_text = ""
    try:
        res = generate_text(
            prompt=user_prompt,
            system_instruction=system_prompt,
            temperature=0.1,
            timeout=40,
            return_provider=True,
        )
        if isinstance(res, tuple):
            answer_text, provider = res
        else:
            answer_text = str(res)
            provider = "gemini"
    except Exception as exc:
        LOGGER.warning("AI генерация недоступна, формируем прямой ответ по базе знаний: %s", exc)
        top_art = matched[0]
        answer_text = (
            f"По вашему запросу найдена инструкция **«{top_art['title']}»** "
            f"(раздел: *{top_art['topic_name']}*):\n\n"
            f"{top_art['content']}\n\n"
            f"**Источник:** Статья базы знаний «{top_art['title']}»"
        )
        provider = "database"

    sources_out = [
        {
            "id": art["id"],
            "title": art["title"],
            "topic_name": art["topic_name"],
            "source_filename": art.get("source_filename") or "",
        }
        for art in matched[:3]
    ]

    return {
        "answer": answer_text.strip(),
        "provider": provider,
        "sources": sources_out,
    }
